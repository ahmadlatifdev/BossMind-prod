  "DD_ENV",
  "DD_VERSION",
  "DD_SITE",
  "DD_TRACE_ENABLED",
  "DEEPSEEK_API_KEY",
  "DEEPSEEK_API_BASE",
  "DEEPSEEK_MODEL_V3",
  "DEEPSEEK_MODEL_R1",
  "KIMI_API_KEY",
  "MOONSHOT_API_KEY",
