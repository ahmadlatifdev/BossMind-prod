/**
 * Keys already bound on ssrclientresumoralive via Secret Manager.
 * Writing them as plain env causes Cloud Run update 400:
 * "Secret environment variable overlaps non secret environment variable".
 */
const SECRET_MANAGER_ONLY_KEYS = new Set([
  "DEEPSEEK_API_KEY",
  "RESEND_API_KEY",
  "RESEND_FROM",
  "TWILIO_ACCOUNT_SID",
  "TWILIO_AUTH_TOKEN",
  "TWILIO_FROM_NUMBER",
  "TWILIO_PHONE_NUMBER",
  "TWILIO_MESSAGING_SERVICE_SID",
]);

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  const text = fs.readFileSync(filePath, "utf8").replace(/^\uFEFF/, "");
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 1) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) out[key] = val;
  }
  return out;
}

function serializeEnv(map) {
  const lines = [
    "# Auto-generated by scripts/sync-firebase-hosting-env.mjs ΓÇö do not commit secrets.",
    `# updated: ${new Date().toISOString()}`,
  ];
  for (const key of Object.keys(map).sort()) {
    const val = String(map[key] ?? "");
    if (val.includes("\n") || val.includes("#")) continue;
    lines.push(`${key}=${val}`);
  }
  lines.push("");
  return lines.join("\n");
}

const local = parseEnvFile(path.join(root, ".env.local"));
const production = parseEnvFile(path.join(root, ".env.production"));
const releaseBuildPath = path.join(root, "config", "resumora-release-build.json");
let releaseMeta = {};
if (fs.existsSync(releaseBuildPath)) {
  try {
    releaseMeta = JSON.parse(fs.readFileSync(releaseBuildPath, "utf8"));
  } catch {
    releaseMeta = {};
  }
}
const merged = stripReservedFunctionsEnv({ ...production });

if (releaseMeta.version) {
  merged.RESUMORA_RELEASE_VERSION = releaseMeta.version;
  merged.NEXT_PUBLIC_RESUMORA_RELEASE_VERSION = releaseMeta.version;
}
if (releaseMeta.releaseId) merged.NEXT_PUBLIC_RESUMORA_RELEASE_ID = releaseMeta.releaseId;
if (releaseMeta.releaseMode) merged.RESUMORA_RELEASE_MODE = releaseMeta.releaseMode;
if (releaseMeta.gitCommit) merged.RESUMORA_RELEASE_GIT_COMMIT = releaseMeta.gitCommit;
if (releaseMeta.gitBranch) merged.RESUMORA_RELEASE_GIT_BRANCH = releaseMeta.gitBranch;
if (releaseMeta.releaseManifestChecksum) {
  merged.RESUMORA_RELEASE_MANIFEST_CHECKSUM = releaseMeta.releaseManifestChecksum;
}
if (releaseMeta.artifactChecksum) merged.RESUMORA_RELEASE_ARTIFACT_CHECKSUM = releaseMeta.artifactChecksum;
if (releaseMeta.approvedSourceChecksum || releaseMeta.release_hash) {
  merged.RESUMORA_RELEASE_HASH = releaseMeta.approvedSourceChecksum || releaseMeta.release_hash;
}
if (releaseMeta.build_id) merged.RESUMORA_RELEASE_BUILD_ID = releaseMeta.build_id;
if (releaseMeta.buildTimestampUtc || releaseMeta.deployed_at) {
  merged.RESUMORA_RELEASE_DEPLOYED_AT = releaseMeta.buildTimestampUtc || releaseMeta.deployed_at;
}
if (releaseMeta.firebaseProject) merged.RESUMORA_FIREBASE_PROJECT = releaseMeta.firebaseProject;
if (releaseMeta.firebaseHostingSite) {
  merged.RESUMORA_FIREBASE_HOSTING_SITE = releaseMeta.firebaseHostingSite;
}
if (releaseMeta.productionApproved === true) merged.RESUMORA_PRODUCTION_APPROVED = "true";

for (const [key, val] of Object.entries(local)) {
  if (SECRET_MANAGER_ONLY_KEYS.has(key)) continue;
  if (SERVER_KEYS.has(key) || key.startsWith("STRIPE_") || key.startsWith("BOSSMIND_")) {
    if (val) merged[key] = val;
  }
}

for (const key of SECRET_MANAGER_ONLY_KEYS) {
  delete merged[key];
}

for (const [key, val] of Object.entries(local)) {
  if (key.startsWith("NEXT_PUBLIC_STRIPE_PRICE_") && val) merged[key] = val;
}

for (const [key, val] of Object.entries(local)) {
  if (key.startsWith("NEXT_PUBLIC_DD_") && val) merged[key] = val;
}

for (const [key, val] of Object.entries(production)) {
  if (key.startsWith("NEXT_PUBLIC_DD_") && val) merged[key] = val;
}

if (!merged.NEON_DATABASE_URL && !merged.DATABASE_URL) {
  console.error(
    "sync-firebase-hosting-env: missing NEON_DATABASE_URL/DATABASE_URL in .env.local ΓÇö cannot deploy API routes."
  );
  process.exit(1);
}

const targets = [
  { path: path.join(root, `.env.${PROJECT_ID}`), includeFramework: false },
  {
    path: path.join(root, ".firebase", "client-resumora-live", "functions", ".env"),
    includeFramework: true,
  },
];

for (const target of targets) {
  const existing = parseEnvFile(target.path);
  let payload = target.includeFramework
    ? { ...FRAMEWORK_ENV, ...existing, ...merged }
    : { ...existing, ...merged };
  for (const key of SECRET_MANAGER_ONLY_KEYS) {
    delete payload[key];
  }
  // Always strip Cloud Functions / Firebase reserved keys from deploy env files.
  payload = stripReservedFunctionsEnv(payload);
  fs.mkdirSync(path.dirname(target.path), { recursive: true });
  fs.writeFileSync(target.path, serializeEnv(payload), "utf8");
}

const keyList = Object.keys(merged).sort();
console.log(
  `sync-firebase-hosting-env: wrote ${targets.length} env files with ${keyList.length} keys (${keyList.join(", ")})`
);
