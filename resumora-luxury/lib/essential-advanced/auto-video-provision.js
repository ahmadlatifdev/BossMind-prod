/**
 * Queue BossMind AI video pipeline jobs when Essential Advanced is purchased.
 */
const { getSqlClient, saveEvent } = require("../shared/neon-memory");
const { listVideoModules } = require("./video-delivery");

async function queueEssentialAdvancedVideoJobs({ planId, sessionId, email, lang = "en" }) {
  if (planId !== "essential_advanced") {
    return { queued: 0, skipped: true, reason: "not_essential_advanced" };
  }

  const sql = getSqlClient();
  if (!sql) {
    return { queued: 0, skipped: true, reason: "database_unavailable" };
  }

  let store;
  try {
    store = require("../orchestration/bossmind-ai-video-store");
  } catch {
    return { queued: 0, skipped: true, reason: "video_store_missing" };
  }

  const db = await store.ensureDb();
  if (!db.ok) {
    return { queued: 0, skipped: true, reason: db.reason || "video_db_unavailable" };
  }

  const locale = lang === "fr" ? "fr" : "en";
  const modules = listVideoModules();
  let queued = 0;

  for (const mod of modules) {
    const title = mod.title?.[locale] || mod.title?.en || mod.id;
    const summary = mod.summary?.[locale] || mod.summary?.en || "";
    const rawScript = [
      `Resumora Essential Advanced — auto-generated client module: ${title}`,
      summary,
      `Locale: ${locale}`,
      email ? `Customer: ${String(email).slice(0, 3)}***` : "",
      sessionId ? `Stripe session: ${sessionId}` : "",
    ]
      .filter(Boolean)
      .join("\n");

    const q = await store.insertQueue(db.sql, {
      title,
      source: "essential_advanced_purchase",
      language: locale,
      status: "script_review",
      auto_publish: false,
      target_platforms: ["client_studio"],
      priority: 2,
      payload: {
        videoId: mod.id,
        planId,
        stripeSessionId: sessionId || null,
        delivery: "essential_advanced_studio",
      },
    });

    await store.insertScript(db.sql, {
      queueId: q.id,
      rawText: rawScript,
      meta: { autoGenerated: true, moduleId: mod.id },
    });

    queued += 1;
  }

  await saveEvent({
    projectKey: store.projectKey(),
    eventType: "essential_advanced.video_jobs_queued",
    source: "auto-video-provision",
    eventKey: sessionId ? `ea-videos:${sessionId}` : `ea-videos:${Date.now()}`,
    payload: { queued, sessionId: sessionId || null, locale },
  }).catch(() => {});

  return { queued, skipped: false };
}

module.exports = { queueEssentialAdvancedVideoJobs };
